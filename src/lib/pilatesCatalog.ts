type Entry = Pick<
  Exercise,
  'id' | 'name' | 'category' | 'equipment' | 'bodyRegion' | 'objective' | 'shortDescription' | 'instructions' | 'variations'
> & {
  level: ExerciseLevel;
  contraindications?: string[];
  /** Descriptions of the inicial / intermediária / final phases */
  phases: [string, string, string];
};

const PHASE_TITLES = ['Posição Inicial', 'Posição Intermediária', 'Posição Final'] as const;
const PHASE_TYPES = ['inicial', 'intermediaria', 'final'] as const;

